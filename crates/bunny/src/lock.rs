//! `bunny.lock`: exactly what a system has.
//!
//! The config says what you *want* ("firefox"); the lock says what you *got*:
//! the snapshot of each package repository (git commit or sync timestamp) and
//! the exact installed version of every package. Copy both files to another
//! machine to describe the same system.
//!
//! Part 1 (this file): write the lock from a system, and compare a system
//! against it. Making `switch` install exactly the locked versions is part 2.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};

use crate::import::strip_version;

const HEADER: &str = "# Generated by `bunny lock`. Don't edit by hand.\n\
                      # It records exactly what this system has, so another machine can match it.\n\n";

#[derive(Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Lock {
    pub version: u32,
    /// Package repositories (`gentoo`, overlays) and the snapshot each was at.
    #[serde(default)]
    pub repos: BTreeMap<String, RepoSnapshot>,
    /// `category/name` (or `category/name:slot` when several slots are
    /// installed) → exact version.
    #[serde(default)]
    pub packages: BTreeMap<String, String>,
}

#[derive(Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct RepoSnapshot {
    /// git commit, for repositories synced with git.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub commit: Option<String>,
    /// Sync time, for repositories synced with rsync / emerge-webrsync.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub timestamp: Option<String>,
}

/// Where the lock lives: next to the config, `bunny.toml` → `bunny.lock`.
pub fn path_for(config: &Path) -> PathBuf {
    config.with_extension("lock")
}

/// Reads the system at `root` into a lock.
pub fn from_system(root: &Path) -> Result<Lock> {
    Ok(Lock {
        version: 1,
        repos: read_repos(root)?,
        packages: installed_packages(root)?,
    })
}

pub fn load(path: &Path) -> Result<Lock> {
    let text = std::fs::read_to_string(path)
        .with_context(|| format!("Couldn't read {}", path.display()))?;
    toml::from_str(&text).with_context(|| {
        format!(
            "{} is damaged. Run `bunny lock` to write a fresh one.",
            path.display()
        )
    })
}

pub fn render(lock: &Lock) -> Result<String> {
    Ok(format!("{HEADER}{}", toml::to_string(lock)?))
}

/// Installed packages from Portage's database (`/var/db/pkg`).
pub fn installed_packages(root: &Path) -> Result<BTreeMap<String, String>> {
    let db = root.join("var/db/pkg");
    // (category/name) → [(slot, version)]
    let mut found: BTreeMap<String, Vec<(String, String)>> = BTreeMap::new();
    let Ok(categories) = std::fs::read_dir(&db) else {
        return Ok(BTreeMap::new());
    };
    for category in categories.flatten() {
        if !category.file_type().is_ok_and(|t| t.is_dir()) {
            continue;
        }
        let cat = category.file_name().to_string_lossy().into_owned();
        for entry in std::fs::read_dir(category.path())
            .with_context(|| format!("Couldn't read {}", category.path().display()))?
            .flatten()
        {
            let pf = entry.file_name().to_string_lossy().into_owned();
            // Portage uses "-MERGING-" folders while installing; skip those.
            if pf.starts_with('-') || !entry.file_type().is_ok_and(|t| t.is_dir()) {
                continue;
            }
            let full = format!("{cat}/{pf}");
            let Some(name) = strip_version(&full) else {
                continue;
            };
            let version = full[name.len() + 1..].to_string();
            let slot = std::fs::read_to_string(entry.path().join("SLOT"))
                .map(|s| s.trim().split('/').next().unwrap_or("0").to_string())
                .unwrap_or_else(|_| "0".to_string());
            found
                .entry(name.to_string())
                .or_default()
                .push((slot, version));
        }
    }

    let mut packages = BTreeMap::new();
    for (name, mut instances) in found {
        if instances.len() == 1 {
            packages.insert(name, instances.remove(0).1);
        } else {
            for (slot, version) in instances {
                packages.insert(format!("{name}:{slot}"), version);
            }
        }
    }
    Ok(packages)
}

/// Snapshots of the package repositories in `/var/db/repos`.
fn read_repos(root: &Path) -> Result<BTreeMap<String, RepoSnapshot>> {
    let mut repos = BTreeMap::new();
    let Ok(entries) = std::fs::read_dir(root.join("var/db/repos")) else {
        return Ok(repos);
    };
    for entry in entries.flatten() {
        if !entry.file_type().is_ok_and(|t| t.is_dir()) {
            continue;
        }
        let dir = entry.path();
        let snapshot = RepoSnapshot {
            commit: git_head(&dir),
            timestamp: std::fs::read_to_string(dir.join("metadata/timestamp.chk"))
                .ok()
                .and_then(|t| t.lines().next().map(|l| l.trim().to_string()))
                .filter(|t| !t.is_empty()),
        };
        if snapshot.commit.is_some() || snapshot.timestamp.is_some() {
            let name = std::fs::read_to_string(dir.join("profiles/repo_name"))
                .map(|n| n.trim().to_string())
                .unwrap_or_else(|_| entry.file_name().to_string_lossy().into_owned());
            repos.insert(name, snapshot);
        }
    }
    Ok(repos)
}

/// The commit a git checkout is at, read straight from `.git` (no git needed).
fn git_head(repo: &Path) -> Option<String> {
    let git = repo.join(".git");
    let head = std::fs::read_to_string(git.join("HEAD")).ok()?;
    let head = head.trim();
    let Some(reference) = head.strip_prefix("ref: ") else {
        return Some(head.to_string()); // detached HEAD
    };
    if let Ok(commit) = std::fs::read_to_string(git.join(reference)) {
        return Some(commit.trim().to_string());
    }
    // Refs can also be packed into one file.
    std::fs::read_to_string(git.join("packed-refs"))
        .ok()?
        .lines()
        .find_map(|line| {
            let (commit, name) = line.split_once(' ')?;
            (name == reference).then(|| commit.to_string())
        })
}

/// How a system differs from its lock.
#[derive(Debug, Default, PartialEq)]
pub struct Drift {
    /// (package, locked version, installed version)
    pub changed: Vec<(String, String, String)>,
    /// In the lock, not installed.
    pub missing: Vec<(String, String)>,
    /// Installed, not in the lock.
    pub extra: Vec<(String, String)>,
    /// (repo, locked snapshot, current snapshot) for repos that moved.
    pub repos: Vec<(String, String, String)>,
}

impl Drift {
    pub fn is_empty(&self) -> bool {
        self.changed.is_empty()
            && self.missing.is_empty()
            && self.extra.is_empty()
            && self.repos.is_empty()
    }

    pub fn render(&self) -> String {
        let mut out = String::new();
        if self.is_empty() {
            out.push_str("✓ Installed versions match bunny.lock exactly.\n");
            return out;
        }
        out.push_str("Compared to bunny.lock:\n");
        for (name, locked, now) in &self.changed {
            let _ = writeln!(out, "  ~ {name}: {now} installed, {locked} locked");
        }
        for (name, version) in &self.missing {
            let _ = writeln!(out, "  - {name}: {version} locked, not installed");
        }
        for (name, version) in &self.extra {
            let _ = writeln!(out, "  + {name}: {version} installed, not in the lock");
        }
        for (repo, locked, now) in &self.repos {
            let _ = writeln!(
                out,
                "  ~ the {repo} package tree moved: {now} now, {locked} locked"
            );
        }
        out.push_str(
            "  To record the system as it is now, run `bunny lock`.\n\
             \x20 (Installing exactly the locked versions comes in a later version of bunny.)\n",
        );
        out
    }
}

fn describe(s: &RepoSnapshot) -> String {
    match (&s.commit, &s.timestamp) {
        (Some(c), _) => format!("commit {}", &c[..c.len().min(12)]),
        (None, Some(t)) => t.clone(),
        (None, None) => "unknown".into(),
    }
}

pub fn compare(locked: &Lock, now: &Lock) -> Drift {
    let mut drift = Drift::default();
    for (name, version) in &locked.packages {
        match now.packages.get(name) {
            Some(v) if v != version => {
                drift
                    .changed
                    .push((name.clone(), version.clone(), v.clone()))
            }
            Some(_) => {}
            None => drift.missing.push((name.clone(), version.clone())),
        }
    }
    for (name, version) in &now.packages {
        if !locked.packages.contains_key(name) {
            drift.extra.push((name.clone(), version.clone()));
        }
    }
    for (repo, snapshot) in &locked.repos {
        if let Some(current) = now.repos.get(repo) {
            if current != snapshot {
                drift
                    .repos
                    .push((repo.clone(), describe(snapshot), describe(current)));
            }
        }
    }
    drift
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write(root: &Path, path: &str, text: &str) {
        let path = root.join(path);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }

    fn fake_system() -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        let r = dir.path();
        write(r, "var/db/pkg/app-misc/tmux-3.6a/SLOT", "0\n");
        write(
            r,
            "var/db/pkg/media-fonts/font-adobe-100dpi-1.0.4-r1/SLOT",
            "0\n",
        );
        write(r, "var/db/pkg/dev-lang/python-3.12.8_p1/SLOT", "3.12\n");
        write(r, "var/db/pkg/dev-lang/python-3.13.2/SLOT", "3.13/3.13t\n");
        std::fs::create_dir_all(r.join("var/db/pkg/app-misc/-MERGING-foo-1")).unwrap();
        write(
            r,
            "var/db/repos/gentoo/metadata/timestamp.chk",
            "Sun, 16 Nov 2026 00:45:01 +0000\n",
        );
        write(r, "var/db/repos/gentoo/profiles/repo_name", "gentoo\n");
        write(r, "var/db/repos/guru/.git/HEAD", "ref: refs/heads/master\n");
        write(
            r,
            "var/db/repos/guru/.git/packed-refs",
            "# pack-refs\nabc123 refs/heads/master\n",
        );
        write(r, "var/db/repos/guru/profiles/repo_name", "guru\n");
        dir
    }

    #[test]
    fn reads_installed_packages() {
        let root = fake_system();
        let packages = installed_packages(root.path()).unwrap();
        assert_eq!(packages["app-misc/tmux"], "3.6a");
        assert_eq!(packages["media-fonts/font-adobe-100dpi"], "1.0.4-r1");
        // Two slots installed: keyed by slot.
        assert_eq!(packages["dev-lang/python:3.12"], "3.12.8_p1");
        assert_eq!(packages["dev-lang/python:3.13"], "3.13.2");
        assert_eq!(packages.len(), 4, "{packages:#?}");
    }

    #[test]
    fn reads_repo_snapshots() {
        let root = fake_system();
        let lock = from_system(root.path()).unwrap();
        assert_eq!(
            lock.repos["gentoo"].timestamp.as_deref(),
            Some("Sun, 16 Nov 2026 00:45:01 +0000")
        );
        assert_eq!(lock.repos["guru"].commit.as_deref(), Some("abc123"));
    }

    #[test]
    fn lock_round_trips() {
        let root = fake_system();
        let lock = from_system(root.path()).unwrap();
        let text = render(&lock).unwrap();
        assert!(text.starts_with("# Generated by `bunny lock`"));
        let path = root.path().join("bunny.lock");
        std::fs::write(&path, text).unwrap();
        assert_eq!(load(&path).unwrap(), lock);
    }

    #[test]
    fn same_system_has_no_drift() {
        let root = fake_system();
        let lock = from_system(root.path()).unwrap();
        let drift = compare(&lock, &from_system(root.path()).unwrap());
        assert!(drift.is_empty());
        assert!(drift.render().contains("match bunny.lock exactly"));
    }

    #[test]
    fn finds_drift() {
        let root = fake_system();
        let locked = from_system(root.path()).unwrap();
        let r = root.path();
        std::fs::rename(
            r.join("var/db/pkg/app-misc/tmux-3.6a"),
            r.join("var/db/pkg/app-misc/tmux-3.7"),
        )
        .unwrap();
        std::fs::remove_dir_all(r.join("var/db/pkg/media-fonts")).unwrap();
        write(r, "var/db/pkg/app-misc/cowsay-3.8/SLOT", "0\n");
        write(
            r,
            "var/db/repos/guru/.git/packed-refs",
            "def456 refs/heads/master\n",
        );

        let drift = compare(&locked, &from_system(r).unwrap());
        assert_eq!(
            drift.changed,
            [("app-misc/tmux".into(), "3.6a".into(), "3.7".into())]
        );
        assert_eq!(drift.missing.len(), 1);
        assert_eq!(drift.extra, [("app-misc/cowsay".into(), "3.8".into())]);
        assert_eq!(drift.repos.len(), 1);
        let text = drift.render();
        assert!(text.contains("tmux: 3.7 installed, 3.6a locked"), "{text}");
    }

    #[test]
    fn lock_path_sits_next_to_the_config() {
        assert_eq!(
            path_for(Path::new("/etc/bunny/bunny.toml")),
            Path::new("/etc/bunny/bunny.lock")
        );
    }
}
