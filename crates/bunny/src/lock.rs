    #[test]
    fn update_syncs_unpins_updates_and_relocks() {
        let root = fake_system();
        let r = root.path();
        write(r, "var/lib/portage/world", "app-misc/tmux\n");
        std::fs::create_dir_all(r.join(".snapshots")).unwrap();
        let config = Config::parse("packages = [\"app-misc/tmux\"]").unwrap();
        let lock_path = r.join("bunny.lock");
        std::fs::write(&lock_path, render(&from_system(r).unwrap()).unwrap()).unwrap();
        write_pins(r, &load(&lock_path).unwrap()).unwrap();

        // Pretend the update installed a newer tmux.
        struct Upgrader(Recorder, PathBuf);
        impl Runner for Upgrader {
            fn run(&mut self, cmd: &[String]) -> Result<bool> {
                if cmd.last().map(String::as_str) == Some("@world") {
                    // The pins must be gone while updating.
                    assert!(!self.1.join(PIN_FILE).exists());
                    std::fs::rename(
                        self.1.join("var/db/pkg/app-misc/tmux-3.6a"),
                        self.1.join("var/db/pkg/app-misc/tmux-3.7"),
                    )
                    .unwrap();
                }
                self.0.run(cmd)
            }
        }
        let mut runner = Upgrader(Recorder::default(), r.to_path_buf());
        let (_, change) = update(&config, r, &lock_path, &mut runner, &opts()).unwrap();

        let commands = &runner.0.commands;
        assert_eq!(commands[0], "emerge --sync");
        assert!(commands[1].starts_with("btrfs subvolume snapshot"));
        assert!(commands[2].starts_with("emerge --update --deep --newuse"));
        assert_eq!(
            change.drift.changed,
            [("app-misc/tmux".into(), "3.6a".into(), "3.7".into())]
        );
        assert_eq!(load(&lock_path).unwrap().packages["app-misc/tmux"], "3.7");
        let pins = std::fs::read_to_string(r.join(PIN_FILE)).unwrap();
        assert!(pins.contains(">app-misc/tmux-3.7"), "{pins}");
    }

